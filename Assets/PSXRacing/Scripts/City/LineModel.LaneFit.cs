using System.Collections.Generic;
using UnityEngine;

namespace PSXRacing.City
{
    /// <summary>
    /// THE ROAD-LINES ROUND, FAULTS 1 + 2 (2026-11-16 night): THE LANE FIT.
    /// The owner on North Tryon Street (PC48, 2.16 km before a STACK BURGER): "the road and/or road lines
    /// do not make sense, are not accurate, and would never pass DOT requirements" - the double yellow
    /// S-jogs mid-road and a solid white line leaves a lane about 8 m wide.
    ///
    /// CAUSE. OSM tags SEVEN lanes there: three each way and a centre lane that is a two-way left-turn
    /// lane, then (on 27-43 m pieces) the westbound left-turn bay of a side street (lanes=7,
    /// lanes:forward=3, lanes:backward=3 / 4, lanes:both_ways=1, turn:lanes:backward=left|none|none|none).
    /// Street level today (viewed only): exactly that - a centre lane between two solid + broken yellow
    /// pairs, three lanes each side, the through lanes dead straight. The widest two-way profile held SIX
    /// lanes ("a seven-lane surface street is painted as six, which nobody driving it will count"), so the
    /// exporter's line set (tools/city/lib/lineset.mjs twoWaySplit) dropped the centre lane where it is a
    /// TWLTL (3 + 3, a double yellow) and, on the bay pieces, "shared the lanes in the tags' proportion":
    /// 2 + 4 - the bay took an OPPOSING THROUGH LANE. The line model then relayed between the two layouts
    /// at each piece's end (LineModel.Relay: half the shifting taper on arms 25-58 m long): over 200 m the
    /// double yellow swung a whole lane left, back, left again and jumped back across a junction (9:1 at
    /// 45 mph where a lane shift needs 45:1), and the opposing side's inner lane line simply ended - one
    /// lane 5.3-7.2 m wide beside the right-turn lane's solid line.
    ///
    /// THE FIX (PSX_CITY_LINEFIX). The game has the seven-lane street (RoadProfiles.Tw7: 3 + TWLTL + 3,
    /// 26.2 m), and every two-way way whose tags carry seven lanes or more draws on it with its OWN lanes
    /// (LineModel.LaneFitList.cs, generated by tools/city/lanefit.mjs from the raw OSM; keyed by OSM way
    /// id - no export, the graph is untouched): 3 + TWLTL + 3, or 3 + 4 with the double yellow on the far
    /// side of the centre lane where it is one direction's bay. The through lanes no longer move; the
    /// relay between a TWLTL piece and a bay piece changes the centre lane's lines and nothing else. A
    /// six-lane piece lying between two seven-lane ones (the mapper left the centre lane out) is lent
    /// 3 + TWLTL + 3. More than seven tagged lanes: the turn lane that does not fit is not drawn.
    ///
    /// THE SAME FIT FOR THE SMALLER STREETS (11-17): a way with a TAGGED centre two-way left-turn lane
    /// whose exported row draws a double yellow, where the lanes add to three or five, takes the profile
    /// the game already has for it (1 + TWLTL + 1, 2 + TWLTL + 2): Parkwood Avenue (lanes=2 +
    /// centre_turn_lane=yes, exported as a plain two-lane street), Sam Newell Road, East Boulevard,
    /// Mallard Creek Road. Four lanes with a centre lane (1 + TWLTL + 2) have no profile: five ways,
    /// 0.2 km, left as exported (tools/city/lanefit.mjs prints them).
    /// </summary>
    public static partial class LineModel
    {
        public static readonly List<string> LaneFitLog = new List<string>();
        /// <summary>Edges given the seven-lane profile and their tagged line set at load.</summary>
        public static int LaneFitEdges;
        /// <summary>Listed ways (the generated table's rows).</summary>
        public static int LaneFitWays => LaneFitData.Length / 6;

        /// <summary>CityMap's loader calls this after LSET and before the line model starts.</summary>
        public static void ApplyLaneFit(CityMap map)
        {
            LaneFitLog.Clear(); LaneFitEdges = 0;
            if (!LineFixOn || map == null || map.edges == null) return;
            var at = new Dictionary<uint, int>();
            for (int i = 0; i + 5 < LaneFitData.Length; i += 6) at[LaneFitData[i]] = i;
            foreach (var e in map.edges)
            {
                if (e == null || e.oneway || e.link || e.a == e.b || e.wayId == 0 || !at.TryGetValue(e.wayId, out int r)) continue;
                if (!LineFixAt(map, e)) continue;
                int lf = (int)LaneFitData[r + 1], lb = (int)LaneFitData[r + 2], both = (int)LaneFitData[r + 3];
                int bf = (int)LaneFitData[r + 4], bb = (int)LaneFitData[r + 5];
                // the profile the tagged lanes need: seven or more -> the seven-lane street; a tagged centre
                // turn lane on three or five lanes -> 1 + TWLTL + 1 / 2 + TWLTL + 2 (RoadProfiles.All 1, 3)
                int total = lf + lb + both;
                int target = total >= 7 ? RoadProfiles.Tw7 : both == 1 && total == 5 ? 3 : both == 1 && total == 3 ? 1 : -1;
                if (target < 0) continue;
                var pr = RoadProfiles.All[target];
                // more than the seven the profile holds: the larger direction's turn lane that does not fit
                // is not drawn (its outer turn lane first, then an inner bay, then a lane)
                string dropped = "";
                for (int g = 0; g < 6 && lf + lb + both > pr.lanes; g++)
                {
                    bool f = lf >= lb;
                    int n = f ? lf : lb, bits = f ? bf : bb;
                    if (n >= 2 && (bits & (1 << (n - 1))) != 0) { bits &= ~(1 << (n - 1)); dropped += " an outer turn lane"; }
                    else if (n >= 2 && (bits & 1) != 0) { bits >>= 1; dropped += " an inner bay"; }
                    else { bits &= (1 << (n - 1)) - 1; dropped += " a lane"; }
                    n--;
                    if (f) { lf = n; bf = bits; } else { lb = n; bb = bits; }
                }
                if (lf < 1 || lb < 1 || lf + lb + both != pr.lanes) continue;
                // the edge's frame: a two-way edge runs with its way (the exporter reverses only a oneway=-1);
                // checked against the exported row's own split and turn bits
                bool flip = false;
                if (e.hasLset)
                {
                    if (e.lsNF != e.lsNB && lf != lb) flip = (e.lsNF > e.lsNB) != (lf > lb);
                    else if (bf != bb) flip = (e.lsTurnOnly & 0xFF) != (bf & 0xFF) && (e.lsTurnOnly & 0xFF) == (bb & 0xFF);
                }
                int nF = flip ? lb : lf, nB = flip ? lf : lb, tF = flip ? bb : bf, tB = flip ? bf : bb;
                if (LaneFitLog.Count < 200)
                    LaneFitLog.Add($"e{e.index} '{e.name}' way {e.wayId} {e.length:0} m: {RoadProfiles.All[e.profile].key} {e.lsNF}+{e.lsNB} centre {e.lsCentre} -> {pr.key} {nF}{(both == 1 ? " + TWLTL" : "")} + {nB} (turn-only f {System.Convert.ToString(tF, 2)} b {System.Convert.ToString(tB, 2)}){(dropped.Length > 0 ? "; not drawn:" + dropped : "")}{(flip ? " [the edge runs against its way]" : "")}");
                e.profile = target;
                e.width = pr.Width; e.shl = pr.shl; e.shr = pr.shr;
                e.lanes = pr.lanes; e.turnLane = both == 1;
                e.hasLset = true;
                e.lsNF = (byte)nF; e.lsNB = (byte)nB; e.lsCentre = (byte)(both == 1 ? 2 : 1);
                e.lsTurnOnly = (ushort)((tF & 0xFF) | ((tB & 0xFF) << 8));
                e.lsFlags = (byte)((e.lsFlags | 1) & ~(2 | 4));
                LaneFitEdges++;
            }
            ApplyCentreRuns(map);
            if (LaneFitEdges > 0 || CentreRunsMade > 0) Debug.Log($"[city] lane fit (PSX_CITY_LINEFIX): {LaneFitEdges} edges on the profile their tagged lanes need, with their own line set ({LaneFitWays} ways listed); {CentreRunsMade} short centre-lane bays ({CentreRunEdges} edges, {CentreRunM:0} m) drawn as two-way left-turn lanes");
        }

        // ================================================================
        //  THE CENTRE LANE'S SHORT RUNS (the road-lines round, 2026-11-17)
        // ================================================================
        // On a street with a centre lane (three, five or seven lanes) the exported rows give that lane, piece
        // by piece, to one direction (its left bay: 2 + 1), to the other (1 + 2) or to both (a two-way
        // left-turn lane). Where two pieces of opposite ownership meet mid-block the double yellow has to
        // cross the centre lane (LineModel.Relay: over the bay taper). A bay that lies BETWEEN two mid-block
        // joins - it ends at no junction of the graph: a driveway's or an unmapped street's - and is too
        // short for its crossing tapers plus 30 m of storage made the double yellow cross over and straight
        // back: the owner's S (East 7th Street 18 times, Gleneagles Road 12, Beam Road 8...). Such a run is
        // drawn as what it is on the street: a two-way left-turn lane. No line moves at either end.
        public static int CentreRunsMade, CentreRunEdges;
        public static float CentreRunM;
        public static readonly List<string> CentreRunLog = new List<string>();

        /// <summary>Whose the centre lane of a marked two-way edge on an odd profile is, in the edge's own
        /// frame: 1 the a-to-b direction's, 2 the other's, 3 both (TWLTL), 0 not such an edge.</summary>
        static int CentreOwner(CityMap.Edge e)
        {
            if (e == null || e.oneway || e.link || e.a == e.b || !e.hasLset || (e.lsFlags & 1) == 0) return 0;
            if (e.profile < 0 || e.profile >= RoadProfiles.All.Length) return 0;
            var pr = RoadProfiles.All[e.profile];
            if (!pr.turnLane || (pr.lanes & 1) == 0) return 0;
            int k = (pr.lanes - 1) / 2;
            if (e.lsCentre == 2) return e.lsNF == k && e.lsNB == k ? 3 : 0;
            if (e.lsCentre != 1) return 0;
            return e.lsNF == k + 1 && e.lsNB == k ? 1 : e.lsNF == k && e.lsNB == k + 1 ? 2 : 0;
        }

        /// <summary>The road's next piece through a two-arm node (same profile), or null.</summary>
        static CityMap.Edge NextPiece(CityMap map, CityMap.Edge e, int node)
        {
            if (node < 0 || node >= map.nodeEdges.Length) return null;
            var l = map.nodeEdges[node];
            if (l == null || l.Count != 2) return null;
            int oi = l[0] == e.index ? l[1] : l[0];
            if (oi == e.index || oi < 0 || oi >= map.edges.Length) return null;
            var o = map.edges[oi];
            return o != null && o.profile == e.profile ? o : null;
        }

        /// <summary>The next piece's centre-lane owner seen in <paramref name="e"/>'s frame (0 none).</summary>
        static int OwnerBeyond(CityMap map, CityMap.Edge e, int node, out CityMap.Edge o)
        {
            o = NextPiece(map, e, node);
            if (o == null) return 0;
            int own = CentreOwner(o);
            bool same = (e.b == node) == (o.a == node);
            return !same && (own == 1 || own == 2) ? 3 - own : own;
        }

        static void ApplyCentreRuns(CityMap map)
        {
            CentreRunsMade = 0; CentreRunEdges = 0; CentreRunM = 0f; CentreRunLog.Clear();
            if (!LineFixOn || map.nodeEdges == null) return;
            var seen = new HashSet<int>();
            var runs = new List<(List<int> edges, float len, float mph, int endA, int nodeA, int endB, int nodeB)>();
            foreach (var e0 in map.edges)
            {
                int own0 = CentreOwner(e0);
                if ((own0 != 1 && own0 != 2) || !seen.Add(e0.index)) continue;
                var list = new List<int> { e0.index };
                float len = e0.length, mph = SpeedMph(e0);
                int[] endE = { e0.index, e0.index }, endN = { e0.a, e0.b };
                for (int side = 0; side < 2; side++)
                {
                    var cur = e0; int node = side == 0 ? e0.a : e0.b;
                    for (int g = 0; g < 64; g++)
                    {
                        int own = OwnerBeyond(map, cur, node, out var o);
                        if (o == null || own != CentreOwner(cur) || !seen.Add(o.index)) break;
                        list.Add(o.index); len += o.length; mph = Mathf.Max(mph, SpeedMph(o));
                        node = o.a == node ? o.b : o.a; cur = o;
                    }
                    endE[side] = cur.index; endN[side] = node;
                }
                runs.Add((list, len, mph, endE[0], endN[0], endE[1], endN[1]));
            }
            runs.Sort((x, y) => x.len.CompareTo(y.len));
            foreach (var r in runs)
            {
                // the flanks as they are NOW (a shorter run beside this one may have become a two-way lane)
                var eA = map.edges[r.endA]; var eB = map.edges[r.endB];
                int fa = OwnerBeyond(map, eA, r.nodeA, out _), fb = OwnerBeyond(map, eB, r.nodeB, out _);
                if (fa == 0 || fb == 0) continue;                       // ends at a junction (or another profile): a real bay
                int nOpp = (fa != 3 && fa != CentreOwner(eA) ? 1 : 0) + (fb != 3 && fb != CentreOwner(eB) ? 1 : 0);
                if (nOpp == 0) continue;                                // a bay inside a two-way lane: no line moves anyway
                float need = 0.5f * RoadProfiles.LaneM * BayTaperRate(r.mph) * nOpp + BayStorageM;
                if (r.len >= need) continue;
                bool skip = false;
                foreach (int ei in r.edges) if (!LineFixAt(map, map.edges[ei])) skip = true;
                if (skip) continue;
                foreach (int ei in r.edges)
                {
                    var e = map.edges[ei];
                    int own = CentreOwner(e);
                    int k = (RoadProfiles.All[e.profile].lanes - 1) / 2;
                    int tF = e.lsTurnOnly & 0xFF, tB = (e.lsTurnOnly >> 8) & 0xFF;
                    if (own == 1) tF >>= 1; else if (own == 2) tB >>= 1; else continue;
                    e.lsNF = (byte)k; e.lsNB = (byte)k; e.lsCentre = 2; e.turnLane = true;
                    e.lsTurnOnly = (ushort)((tF & 0xFF) | ((tB & 0xFF) << 8));
                    CentreRunEdges++;
                }
                CentreRunsMade++; CentreRunM += r.len;
                if (CentreRunLog.Count < 300)
                    CentreRunLog.Add($"e{r.edges[0]} '{map.edges[r.edges[0]].name}' {r.len:0} m ({r.edges.Count} pieces, {r.mph:0} mph): a centre-lane bay between {(nOpp == 2 ? "two opposing bays" : "an opposing bay and a two-way lane")}, short of {need:0} m: drawn as a two-way left-turn lane");
            }
        }
    }
}
