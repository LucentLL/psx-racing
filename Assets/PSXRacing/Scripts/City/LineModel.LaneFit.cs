using System.Collections.Generic;
using UnityEngine;

namespace PSXRacing.City
{
    /// <summary>
    /// THE ROAD-LINES ROUND, FAULTS 1 + 2 (2026-11-16 night): THE LANE FIT.
    /// The owner on North Tryon Street (PC48, 2.16 km before a STACK BURGER): "the road and/or road lines
    /// do not make sense, are not accurate, and would never pass DOT requirements" - the double yellow
    /// S-jogs mid-road and a solid white line leaves a lane about 8 m wide.
    ///
    /// CAUSE. OSM tags SEVEN lanes there: three each way and a centre lane that is a two-way left-turn
    /// lane, then (on 27-43 m pieces) the westbound left-turn bay of a side street (lanes=7,
    /// lanes:forward=3, lanes:backward=3 / 4, lanes:both_ways=1, turn:lanes:backward=left|none|none|none).
    /// Street level today (viewed only): exactly that - a centre lane between two solid + broken yellow
    /// pairs, three lanes each side, the through lanes dead straight. The widest two-way profile held SIX
    /// lanes ("a seven-lane surface street is painted as six, which nobody driving it will count"), so the
    /// exporter's line set (tools/city/lib/lineset.mjs twoWaySplit) dropped the centre lane where it is a
    /// TWLTL (3 + 3, a double yellow) and, on the bay pieces, "shared the lanes in the tags' proportion":
    /// 2 + 4 - the bay took an OPPOSING THROUGH LANE. The line model then relayed between the two layouts
    /// at each piece's end (LineModel.Relay: half the shifting taper on arms 25-58 m long): over 200 m the
    /// double yellow swung a whole lane left, back, left again and jumped back across a junction (9:1 at
    /// 45 mph where a lane shift needs 45:1), and the opposing side's inner lane line simply ended - one
    /// lane 5.3-7.2 m wide beside the right-turn lane's solid line.
    ///
    /// THE FIX (PSX_CITY_LINEFIX). The game has the seven-lane street (RoadProfiles.Tw7: 3 + TWLTL + 3,
    /// 26.2 m), and every two-way way whose tags carry seven lanes or more draws on it with its OWN lanes
    /// (LineModel.LaneFitList.cs, generated by tools/city/lanefit.mjs from the raw OSM; keyed by OSM way
    /// id - no export, the graph is untouched): 3 + TWLTL + 3, or 3 + 4 with the double yellow on the far
    /// side of the centre lane where it is one direction's bay. The through lanes no longer move; the
    /// relay between a TWLTL piece and a bay piece changes the centre lane's lines and nothing else. A
    /// six-lane piece lying between two seven-lane ones (the mapper left the centre lane out) is lent
    /// 3 + TWLTL + 3. More than seven tagged lanes: the turn lane that does not fit is not drawn.
    /// </summary>
    public static partial class LineModel
    {
        public static readonly List<string> LaneFitLog = new List<string>();
        /// <summary>Edges given the seven-lane profile and their tagged line set at load.</summary>
        public static int LaneFitEdges;
        /// <summary>Listed ways (the generated table's rows).</summary>
        public static int LaneFitWays => LaneFitData.Length / 6;

        /// <summary>CityMap's loader calls this after LSET and before the line model starts.</summary>
        public static void ApplyLaneFit(CityMap map)
        {
            LaneFitLog.Clear(); LaneFitEdges = 0;
            if (!LineFixOn || map == null || map.edges == null) return;
            var at = new Dictionary<uint, int>();
            for (int i = 0; i + 5 < LaneFitData.Length; i += 6) at[LaneFitData[i]] = i;
            var pr = RoadProfiles.All[RoadProfiles.Tw7];
            foreach (var e in map.edges)
            {
                if (e == null || e.oneway || e.link || e.a == e.b || e.wayId == 0 || !at.TryGetValue(e.wayId, out int r)) continue;
                int lf = (int)LaneFitData[r + 1], lb = (int)LaneFitData[r + 2], both = (int)LaneFitData[r + 3];
                int bf = (int)LaneFitData[r + 4], bb = (int)LaneFitData[r + 5];
                // more than the seven the profile holds: the larger direction's turn lane that does not fit
                // is not drawn (its outer turn lane first, then an inner bay, then a lane)
                string dropped = "";
                for (int g = 0; g < 6 && lf + lb + both > pr.lanes; g++)
                {
                    bool f = lf >= lb;
                    int n = f ? lf : lb, bits = f ? bf : bb;
                    if (n >= 2 && (bits & (1 << (n - 1))) != 0) { bits &= ~(1 << (n - 1)); dropped += " an outer turn lane"; }
                    else if (n >= 2 && (bits & 1) != 0) { bits >>= 1; dropped += " an inner bay"; }
                    else { bits &= (1 << (n - 1)) - 1; dropped += " a lane"; }
                    n--;
                    if (f) { lf = n; bf = bits; } else { lb = n; bb = bits; }
                }
                if (lf < 1 || lb < 1 || lf + lb + both != pr.lanes) continue;
                // the edge's frame: a two-way edge runs with its way (the exporter reverses only a oneway=-1);
                // checked against the exported row's own split and turn bits
                bool flip = false;
                if (e.hasLset)
                {
                    if (e.lsNF != e.lsNB && lf != lb) flip = (e.lsNF > e.lsNB) != (lf > lb);
                    else if (bf != bb) flip = (e.lsTurnOnly & 0xFF) != (bf & 0xFF) && (e.lsTurnOnly & 0xFF) == (bb & 0xFF);
                }
                int nF = flip ? lb : lf, nB = flip ? lf : lb, tF = flip ? bb : bf, tB = flip ? bf : bb;
                if (LaneFitLog.Count < 200)
                    LaneFitLog.Add($"e{e.index} '{e.name}' way {e.wayId} {e.length:0} m: {RoadProfiles.All[e.profile].key} {e.lsNF}+{e.lsNB} centre {e.lsCentre} -> {pr.key} {nF}{(both == 1 ? " + TWLTL" : "")} + {nB} (turn-only f {System.Convert.ToString(tF, 2)} b {System.Convert.ToString(tB, 2)}){(dropped.Length > 0 ? "; not drawn:" + dropped : "")}{(flip ? " [the edge runs against its way]" : "")}");
                e.profile = RoadProfiles.Tw7;
                e.width = pr.Width; e.shl = pr.shl; e.shr = pr.shr;
                e.lanes = pr.lanes; e.turnLane = both == 1;
                e.hasLset = true;
                e.lsNF = (byte)nF; e.lsNB = (byte)nB; e.lsCentre = (byte)(both == 1 ? 2 : 1);
                e.lsTurnOnly = (ushort)((tF & 0xFF) | ((tB & 0xFF) << 8));
                e.lsFlags = (byte)((e.lsFlags | 1) & ~(2 | 4));
                LaneFitEdges++;
            }
            if (LaneFitEdges > 0) Debug.Log($"[city] lane fit (PSX_CITY_LINEFIX): {LaneFitEdges} edges on the seven-lane profile with their tagged lanes ({LaneFitWays} ways listed)");
        }
    }
}
